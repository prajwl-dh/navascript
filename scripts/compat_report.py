"""Deterministic Markdown rendering for the compatibility corpus report."""

from __future__ import annotations

from typing import Any, Iterable

OUTCOMES = ("pass", "fail", "blocked", "skip")


def render_report(cases: Iterable[Any], results: dict[str, str]) -> str:
    """Render a report from case metadata and outcomes.

    Sorting here makes the report deterministic even when a caller supplies
    cases in discovery (filesystem) order. Case values only need the attributes
    declared by ``compat_core.Case``; importing that module here would create a
    cycle with the harness orchestration.
    """

    ordered = sorted(cases, key=lambda item: item.id)
    counts = {outcome: sum(results[case.id] == outcome for case in ordered) for outcome in OUTCOMES}
    executed = counts["pass"] + counts["fail"]
    rate = (100.0 * counts["pass"] / executed) if executed else 0.0
    lines = [
        "# NavaScript — Measured TypeScript Compatibility Report",
        "",
        "Generated by `scripts/compat.py` from the corpus in",
        "`tests/compatibility/corpus/`. To reproduce this report, run:",
        "",
        "```bash",
        "cargo build --workspace",
        "python3 scripts/compat.py --report docs/COMPATIBILITY_REPORT.md",
        "```",
        "",
        "The report is deliberately free of timestamps, tool versions and machine",
        "paths, so a rerun with the same toolchain is byte-identical. The reference",
        "is the runtime behaviour of the JavaScript emitted by `tsc` (which emits",
        "even when it reports type errors); `type_error` records that deliberate",
        "choice. Skipped cases are declared from `COMPATIBILITY.md` §6 and are not",
        "executed. Known-difference cases pin both the reference output and the",
        "expected NavaScript outcome, so an arbitrary failure cannot count as a pass.",
        "",
        "## Summary",
        "",
        "| Outcome | Cases |",
        "| --- | ---: |",
        f"| Passed (observed behaviour matched the expectation) | {counts['pass']} |",
        f"| Failed (behaviour contradicted the expectation) | {counts['fail']} |",
        f"| Skipped (documented unsupported feature) | {counts['skip']} |",
        f"| Blocked (tool unavailable) | {counts['blocked']} |",
        f"| **Total** | **{len(ordered)}** |",
        "",
        f"Executed-pass rate: {rate:.1f}% ({counts['pass']}/{executed} executed cases).",
        "",
        "## Results",
        "",
        "| Case | Category | Expectation | Outcome | Title |",
        "| --- | --- | --- | --- | --- |",
    ]
    for case in ordered:
        title = case.title.replace("|", "\\|")
        lines.append(
            f"| `{case.id}` | {case.category} | {case.expect} | "
            f"{results[case.id]} | {title} |"
        )
    lines.extend(["", "## Known differences and skipped cases", ""])
    documented = [case for case in ordered if case.expect != "match"]
    if documented:
        for case in documented:
            lines.extend(
                [
                    f"### `{case.id}` — {case.title}",
                    "",
                    f"- Expectation: {case.expect} (outcome: {results[case.id]})",
                    f"- Reason: {case.reason}",
                ]
            )
            if case.reference_output is not None:
                lines.append(f"- Measured Node output: `{case.reference_output}`")
            lines.append("")
    else:
        lines.extend(["None.", ""])
    failures = [case for case in ordered if results[case.id] == "fail"]
    lines.extend(["## Failures", ""])
    if failures:
        for case in failures:
            lines.extend([f"- `{case.id}` — {case.title}", ""])
    else:
        lines.extend(["None.", ""])
    return "\n".join(lines) + "\n"
