#!/usr/bin/env python3
"""Reproducible Phase 8 benchmark runner.

For each program in ``benchmarks/`` this builds an unoptimized baseline
(``--no-opt``) and an optimized binary (``--release``), checks that they print
the same output, counts LLVM IR instructions in both pipelines, and measures
wall-clock medians. Instruction counts and output checks are deterministic;
timings are machine-specific but measured by the same commands everywhere.
"""

from __future__ import annotations

import argparse
import re
import statistics
import subprocess
import sys
import tempfile
import time
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BENCHMARKS = ROOT / "benchmarks"
DEFAULT_BINARY = ROOT / "target" / "debug" / "navascript"
DEFAULT_REPORT = ROOT / "docs" / "BENCHMARKS.md"


@dataclass(frozen=True)
class Measurement:
    name: str
    baseline_ir: int
    optimized_ir: int
    baseline_ms: float
    optimized_ms: float
    output_matches: bool

    @property
    def reduction(self) -> float:
        if self.baseline_ir == 0:
            return 0.0
        return 100.0 * (self.baseline_ir - self.optimized_ir) / self.baseline_ir

    @property
    def speedup(self) -> float:
        if self.optimized_ms == 0:
            return 0.0
        return self.baseline_ms / self.optimized_ms


def run(command: list[object], timeout: int = 180) -> tuple[str, int]:
    completed = subprocess.run(
        [str(part) for part in command],
        capture_output=True,
        timeout=timeout,
        check=False,
    )
    return completed.stdout.decode("utf-8", errors="replace"), completed.returncode


def instruction_count(ir: str) -> int:
    """Count emitted LLVM instructions (indented lines), ignoring declarations."""

    return sum(1 for line in ir.splitlines() if line.startswith("  "))


def build(binary: Path, source: Path, output: Path, optimized: bool) -> str | None:
    flags = ["--release"] if optimized else ["--no-opt"]
    _, code = run([binary, "build", *flags, source, "-o", output])
    return None if code == 0 else f"build failed for {source.name} ({flags})"


def elapsed(binary: Path, runs: int) -> float:
    samples: list[float] = []
    for _ in range(runs):
        start = time.perf_counter()
        _, code = run([binary])
        samples.append((time.perf_counter() - start) * 1000.0)
        if code != 0:
            return float("inf")
    return statistics.median(samples)


def measure(binary: Path, source: Path, workdir: Path, runs: int) -> Measurement | None:
    baseline = workdir / f"{source.stem}-baseline"
    optimized = workdir / f"{source.stem}-optimized"
    for target, use_opt in ((baseline, False), (optimized, True)):
        error = build(binary, source, target, use_opt)
        if error:
            print(error, file=sys.stderr)
            return None

    base_out, base_code = run([baseline])
    opt_out, opt_code = run([optimized])
    matches = base_code == 0 and opt_code == 0 and base_out == opt_out

    base_ir, base_status = run([binary, "build", "--no-opt", "--emit-ir", source])
    opt_ir, opt_status = run([binary, "build", "--release", "--emit-ir", source])
    if base_status != 0 or opt_status != 0:
        print(f"--emit-ir failed for {source.name}", file=sys.stderr)
        return None

    return Measurement(
        name=source.stem,
        baseline_ir=instruction_count(base_ir),
        optimized_ir=instruction_count(opt_ir),
        baseline_ms=elapsed(baseline, runs),
        optimized_ms=elapsed(optimized, runs),
        output_matches=matches,
    )


ROW_PATTERN = re.compile(
    r"^\| `([^`]+)` \| (\d+) \| (\d+) \| (-?[\d.]+)% \| "
    r"[\d.]+ \| [\d.]+ \| [\d.]+x \| (match|MISMATCH) \|$"
)


def committed_facts(report: str) -> dict[str, tuple[int, int, float, str]]:
    """Deterministic facts read from a committed report (timings excluded)."""

    facts: dict[str, tuple[int, int, float, str]] = {}
    for line in report.splitlines():
        match = ROW_PATTERN.match(line)
        if match:
            facts[match.group(1)] = (
                int(match.group(2)),
                int(match.group(3)),
                float(match.group(4)),
                match.group(5),
            )
    return facts


def measured_facts(results: list[Measurement]) -> dict[str, tuple[int, int, float, str]]:
    return {
        result.name: (
            result.baseline_ir,
            result.optimized_ir,
            round(result.reduction, 1),
            "match" if result.output_matches else "MISMATCH",
        )
        for result in results
    }


def render_report(results: list[Measurement]) -> str:
    lines = [
        "# NavaScript — Phase 8 Benchmarks",
        "",
        "Generated by `scripts/benchmark.py`. To reproduce:",
        "",
        "```bash",
        "cargo build --workspace",
        "python3 scripts/benchmark.py",
        "```",
        "",
        "Each program is built twice: `--no-opt` (baseline) and `--release`",
        "(IR passes + LLVM `opt -passes=default<O3>`). Instruction counts are the",
        "number of indented LLVM IR lines and are deterministic; millisecond",
        "timings are medians of repeated native runs and depend on the machine.",
        "Both builds must print identical output.",
        "",
        "| Benchmark | Baseline IR | Optimized IR | Reduction | Baseline ms | Optimized ms | Speedup | Output |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for result in sorted(results, key=lambda item: item.name):
        output = "match" if result.output_matches else "MISMATCH"
        lines.append(
            f"| `{result.name}` | {result.baseline_ir} | {result.optimized_ir} | "
            f"{result.reduction:.1f}% | {result.baseline_ms:.2f} | "
            f"{result.optimized_ms:.2f} | {result.speedup:.2f}x | {output} |"
        )
    total_base = sum(result.baseline_ir for result in results)
    total_opt = sum(result.optimized_ir for result in results)
    matches = sum(result.output_matches for result in results)
    speedups = [result.speedup for result in results]
    lines.extend(
        [
            "",
            "## Summary",
            "",
            f"- Benchmarks: {len(results)}",
            f"- Output matches: {matches}/{len(results)}",
            f"- LLVM IR instructions: {total_base} → {total_opt}",
            f"- Wall-clock speedups above 1x: {sum(value > 1 for value in speedups)}/{len(speedups)}",
            f"- Median speedup: {statistics.median(speedups):.2f}x" if speedups else "- Median speedup: n/a",
            "- An LLVM pass can increase instruction counts while unrolling a loop;",
            "  wall-clock time, not instruction count alone, is the decisive metric.",
            "",
        ]
    )
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=Path, default=DEFAULT_BINARY)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    parser.add_argument("--runs", type=int, default=5, help="runs per timing sample")
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the report covers every benchmark and outputs match; ignore timings",
    )
    args = parser.parse_args(argv)

    sources = sorted(BENCHMARKS.glob("*.ns"))
    if not sources:
        print(f"no benchmarks in {BENCHMARKS}", file=sys.stderr)
        return 2
    binary = args.binary if args.binary.is_absolute() else ROOT / args.binary
    if not binary.is_file():
        print(f"compiler not built: {binary}", file=sys.stderr)
        return 2

    results: list[Measurement] = []
    with tempfile.TemporaryDirectory(prefix="navascript-bench-") as tmp:
        workdir = Path(tmp)
        for source in sources:
            measurement = measure(binary, source, workdir, 1 if args.check else args.runs)
            if measurement is None:
                return 2
            results.append(measurement)

    report = render_report(results)
    if args.check:
        current = args.report.read_text(encoding="utf-8") if args.report.is_file() else ""
        expected = measured_facts(results)
        actual = committed_facts(current)
        if actual != expected or "Output matches:" not in current:
            print(
                f"benchmark report is stale: expected {expected}, committed {actual}",
                file=sys.stderr,
            )
            return 1
        print(f"benchmark report matches {len(results)} freshly measured benchmarks")
        return 0

    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(report, encoding="utf-8")
    if not all(result.output_matches for result in results):
        print("benchmark outputs differ between baseline and optimized builds", file=sys.stderr)
        return 1
    print(f"wrote {args.report} ({len(results)} benchmarks)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
